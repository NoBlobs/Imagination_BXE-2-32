"""Generate src/include/sfid.h from the public upstream trace-ID table.

The public header pvr_rogue_fwif_sf.h (drm/imagination, GPL-2.0 OR MIT) lists
every firmware trace entry as ROGUE_FW_LOG_CREATESFID(id, group, nparams) plus
a format string.  The firmware only needs the packed SFID words, so this
script emits one macro per entry:

    #define SFID_<GROUP>_<id>  0x7....... /* nparams: "format" */
"""
import re
import sys

GROUPS = ["NULL", "MAIN", "CLEANUP", "CSW", "PM", "RTD", "SPM", "MTS", "BIF",
          "MISC", "POW", "HWR", "HWP", "RPM", "DMA", "DBG"]


def main(src, dst):
    text = open(src, encoding="utf-8").read()
    pat = re.compile(r"ROGUE_FW_LOG_CREATESFID\((\d+),\s*ROGUE_FW_GROUP_(\w+),\s*(\d+)\)\s*,\s*"
                     r"((?:\"(?:[^\"\\]|\\.)*\"\s*)+)\}", re.S)
    out = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
           "/* Generated by tools/gen_sfids.py from the public pvr_rogue_fwif_sf.h. */",
           "#pragma once", ""]
    seen = set()
    for m in pat.finditer(text):
        sid, grp, npar = int(m.group(1)), m.group(2), int(m.group(3))
        if grp not in GROUPS:
            continue
        key = (grp, sid)
        if key in seen:
            continue
        seen.add(key)
        fmt = " ".join(s.strip() for s in re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(4)))
        fmt = fmt.replace("*/", "* /")
        val = sid | (GROUPS.index(grp) << 12) | (npar << 16) | 0x70000000
        out.append(f"#define SFID_{grp}_{sid} 0x{val:08X}u /* {npar}: {fmt} */")
    out.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(seen)} trace IDs written to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
